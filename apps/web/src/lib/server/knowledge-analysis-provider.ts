import 'server-only';

import type {
  KnowledgeArtifactSummary,
  KnowledgeProviderStatus,
  KnowledgeRisk,
} from '@app-starter/shared';
import { z } from 'zod';
import { TriggerwareClient } from 'triggerware';
import { DEMO_EMPLOYEE, DEMO_RISKS } from '@/data/handoff-demo';

const TRIGGERWARE_AGENT_NAME = process.env.TRIGGERWARE_RISK_AGENT ?? 'knowledge-risk-scanner';
const TRIGGERWARE_TIMEOUT_MS = 2_500;

const riskSchema = z.object({
  id: z.string().min(1),
  title: z.string().min(1),
  severity: z.enum(['HIGH', 'MEDIUM', 'LOW']),
  whyOnlyEmployeeKnows: z.string().min(1),
  missingKnowledge: z.string().min(1),
  evidenceFiles: z.array(z.string().min(1)).min(2),
});

const scanOutputSchema = z.object({
  risks: z.array(riskSchema).min(1).max(5),
});

const DEMO_PROVIDER_STATUS: KnowledgeProviderStatus = {
  mode: 'DEMO',
  label: 'Demo fallback',
  isConnected: false,
  detail: 'Deterministic responses keep the demo available without external services.',
};

const withTimeout = async <T>(promise: Promise<T>, timeoutMs: number): Promise<T> => {
  let timeout: ReturnType<typeof setTimeout> | undefined;
  const timeoutPromise = new Promise<never>((_, reject) => {
    timeout = setTimeout(() => reject(new Error('Triggerware connection timed out')), timeoutMs);
  });

  try {
    return await Promise.race([promise, timeoutPromise]);
  } finally {
    if (timeout) clearTimeout(timeout);
  }
};

const getAddress = (): string | null => {
  const address = process.env.TRIGGERWARE_ADDRESS?.trim();
  return address || null;
};

const triggerwareStatus = (detail: string): KnowledgeProviderStatus => ({
  mode: 'TRIGGERWARE',
  label: 'Triggerware agent',
  isConnected: true,
  detail,
});

export const getKnowledgeProviderStatus = async (): Promise<KnowledgeProviderStatus> => {
  const address = getAddress();
  if (!address) return DEMO_PROVIDER_STATUS;

  let client: TriggerwareClient | null = null;
  try {
    client = await withTimeout(TriggerwareClient.connectTcp(address), TRIGGERWARE_TIMEOUT_MS);
    const [health, agents] = await Promise.all([
      withTimeout(client.system.health(), TRIGGERWARE_TIMEOUT_MS),
      withTimeout(client.agents.list(), TRIGGERWARE_TIMEOUT_MS),
    ]);
    const hasRiskAgent = agents.includes(TRIGGERWARE_AGENT_NAME);

    if (!hasRiskAgent) {
      return {
        ...DEMO_PROVIDER_STATUS,
        detail: `Triggerware is healthy (${health.status}), but ${TRIGGERWARE_AGENT_NAME} is not installed yet.`,
      };
    }

    return triggerwareStatus(
      `Connected to ${TRIGGERWARE_AGENT_NAME}; server status ${health.status}.`,
    );
  } catch (error) {
    const message = error instanceof Error ? error.message : 'Unknown connection error';
    return {
      ...DEMO_PROVIDER_STATUS,
      detail: `Triggerware unavailable (${message}). Using deterministic responses.`,
    };
  } finally {
    await client?.close().catch(() => undefined);
  }
};

export interface KnowledgeScanResult {
  risks: KnowledgeRisk[];
  provider: KnowledgeProviderStatus;
}

export const scanKnowledgeRisks = async (
  artifacts: KnowledgeArtifactSummary[],
): Promise<KnowledgeScanResult> => {
  const address = getAddress();
  if (!address) {
    return { risks: DEMO_RISKS, provider: DEMO_PROVIDER_STATUS };
  }

  let client: TriggerwareClient | null = null;
  try {
    client = await withTimeout(TriggerwareClient.connectTcp(address), TRIGGERWARE_TIMEOUT_MS);
    const output = await withTimeout(
      client.agents.run(TRIGGERWARE_AGENT_NAME, {
        employee: DEMO_EMPLOYEE,
        artifacts,
      }),
      15_000,
    );
    const parsedOutput = scanOutputSchema.parse(output);

    return {
      risks: parsedOutput.risks,
      provider: triggerwareStatus(`Generated by ${TRIGGERWARE_AGENT_NAME}.`),
    };
  } catch (error) {
    const message = error instanceof Error ? error.message : 'Unknown agent error';
    return {
      risks: DEMO_RISKS,
      provider: {
        ...DEMO_PROVIDER_STATUS,
        detail: `Triggerware scan failed (${message}). Returned the verified demo result.`,
      },
    };
  } finally {
    await client?.close().catch(() => undefined);
  }
};
